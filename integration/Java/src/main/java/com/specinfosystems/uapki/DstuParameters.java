    /**
     * Визначає параметр ключа ДСТУ 4145 за DER-кодованими параметрами (OID або структура параметрів)
     *
     * @param value DER-кодовані параметри
     * @return параметр ключа
     * @throws UapkiException якщо параметр не підтримується
     */
    public static KeyParameter getKeyParameterByValue(byte[] value) {
        if (value[0] == 0x06) {
            if (Arrays.equals(value, DSTU4145_M233_PB_OID)) return KeyParameter.M233_PB;
            if (Arrays.equals(value, DSTU4145_M257_PB_OID)) return KeyParameter.M257_PB;
            if (Arrays.equals(value, DSTU4145_M307_PB_OID)) return KeyParameter.M307_PB;
            if (Arrays.equals(value, DSTU4145_M367_PB_OID)) return KeyParameter.M367_PB;
            if (Arrays.equals(value, DSTU4145_M431_PB_OID)) return KeyParameter.M431_PB;
        }

        if (value[0] == 0x30) {
            // take first sequence item
            int offset = 2;

            if ((value[1] & 0x80) == 0x80)
                offset += value[1] & 0xF;

            int size;
            if ((value[offset + 1] & 0xFF) == 0x81) size = (value[offset + 2] & 0xFF) + 3;
            else size = (value[offset + 1] & 0xFF) + 2;

            byte[] a = Arrays.copyOfRange(value, offset, offset + size);

            if (matches(a, DSTU4145_M233_PB_OID, DSTU4145_M233_PB_LE, DSTU4145_M233_PB_BE)) return KeyParameter.M233_PB;
            if (matches(a, DSTU4145_M257_PB_OID, DSTU4145_M257_PB_LE, DSTU4145_M257_PB_BE)) return KeyParameter.M257_PB;
            if (matches(a, DSTU4145_M307_PB_OID, DSTU4145_M307_PB_LE, DSTU4145_M307_PB_BE)) return KeyParameter.M307_PB;
            if (matches(a, DSTU4145_M367_PB_OID, DSTU4145_M367_PB_LE, DSTU4145_M367_PB_BE)) return KeyParameter.M367_PB;
            if (matches(a, DSTU4145_M431_PB_OID, DSTU4145_M431_PB_LE, DSTU4145_M431_PB_BE)) return KeyParameter.M431_PB;
        }

        throw new UapkiException("Непідтримуваний параметр ключа");
    }

    private static boolean matches(byte[] a, byte[]... candidates) {
        for (byte[] c : candidates) {
            if (Arrays.equals(a, c))
                return true;
        }
        return false;
    }
